import fs from "node:fs"
const src = fs.readFileSync("client.js", "utf8")
const cssStart = src.indexOf("const CSS = `")
const cssEnd = src.indexOf("`\n\n    /**\n     * 页面样式")
const css = src.slice(cssStart, cssEnd)
const defined = new Set([...css.matchAll(/\.(omb-[a-zA-Z0-9-]+)/g)].map(m => m[1]))
const used = new Set()
for (const m of src.matchAll(/className: '([^']+)'/g)) for (const c of m[1].split(/\s+/)) if (c) used.add(c)
for (const m of src.matchAll(/className: `([^`]+)`/g)) for (const c of m[1].replace(/\$\{[^}]*\}/g, " ").split(/\s+/)) if (c) used.add(c)
for (const m of src.matchAll(/className: ([a-zA-Z]+)\b/g)) if (m[1] !== "undefined") used.add("(dynamic)" + m[1])
const missing = [...used].filter(c => !c.startsWith("(") && !defined.has(c))
const unused = [...defined].filter(c => !used.has(c))
console.log("defined:", defined.size, "used:", used.size)
console.log("used-but-undefined:", missing)
console.log("defined-but-unused:", unused)
