import fs from 'node:fs'
const src = fs.readFileSync('client.js', 'utf8')
const used = new Set([...src.matchAll(/\bt\('([a-zA-Z][a-zA-Z0-9]*)'\)/g)].map(m => m[1]))
const zhBlock = src.slice(src.indexOf('const zh = {'), src.indexOf('const en = {'))
const enBlock = src.slice(src.indexOf('const en = {'), src.indexOf('/** 拼出接口地址'))
const keysOf = block => new Set([...block.matchAll(/^\s{6}([a-zA-Z][a-zA-Z0-9]*):/gm)].map(m => m[1]))
const zh = keysOf(zhBlock)
const en = keysOf(enBlock)
const missingZh = [...used].filter(k => !zh.has(k))
const missingEn = [...used].filter(k => !en.has(k))
const unused = [...zh].filter(k => !used.has(k) && !en.has(k))
const zhOnly = [...zh].filter(k => !en.has(k))
const enOnly = [...en].filter(k => !zh.has(k))
console.log('used keys:', used.size, 'zh:', zh.size, 'en:', en.size)
console.log('missingZh', missingZh)
console.log('missingEn', missingEn)
console.log('zhOnly', zhOnly)
console.log('enOnly', enOnly)
console.log('unusedBoth', unused)
